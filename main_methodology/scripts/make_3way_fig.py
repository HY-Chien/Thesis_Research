#!/usr/bin/env python3
"""Plot the final-system retrieval-after-decomposition ablation.

The source JSON is generated by ``analyze_tlsum_fixA_step_gate_final.py`` from
the tracked fixed-chain traces.  The plotted metric is final-system EM, as in
the thesis table and caption; it is not decomposition-candidate-only EM.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = ROOT / "results/reproduced/tlsum_fixA_step_gate_final.json"
DEFAULT_OUT = ROOT / "results/reproduced/fig_3way_ablation.png"
DATASET_KEYS = ("hotpotqa", "2wiki", "musique", "popqa")
DATASET_LABELS = ("HotpotQA", "2Wiki", "MuSiQue", "PopQA")
ACCURACY_FIRST_POLICY = "tau_0.002305"


def load_values(path: Path) -> tuple[np.ndarray, np.ndarray, np.ndarray, float]:
    results = json.loads(path.read_text(encoding="utf-8"))["results"]
    never = np.asarray([results[ds]["never"]["em"] for ds in DATASET_KEYS])
    accuracy_first = np.asarray([
        results[ds][ACCURACY_FIRST_POLICY]["em"] for ds in DATASET_KEYS
    ])
    always = np.asarray([results[ds]["always"]["em"] for ds in DATASET_KEYS])
    retrieved = sum(
        results[ds][ACCURACY_FIRST_POLICY]["retrieved_steps"]
        for ds in DATASET_KEYS
    )
    total = sum(
        results[ds][ACCURACY_FIRST_POLICY]["total_steps"]
        for ds in DATASET_KEYS
    )
    return never, accuracy_first, always, 100.0 * retrieved / total


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--input", type=Path, default=DEFAULT_INPUT,
        help="machine-readable fixed-chain replay JSON",
    )
    parser.add_argument(
        "--out", type=Path, default=DEFAULT_OUT,
        help="output PNG (default: results/reproduced)",
    )
    args = parser.parse_args()

    never, accuracy_first, always, gate_retrieval = load_values(args.input)
    x = np.arange(len(DATASET_LABELS))
    width = 0.24

    fig, ax = plt.subplots(figsize=(9.4, 5.4), dpi=170)
    bars_never = ax.bar(
        x - width, never, width, label="Never retrieve (0%)", color="#c05a47",
    )
    bars_accuracy = ax.bar(
        x, accuracy_first, width,
        label=rf"Tail-Leakage gate ($\tau=0.002305$; {gate_retrieval:.2f}%)",
        color="#27ae60",
    )
    bars_always = ax.bar(
        x + width, always, width, label="Always retrieve (100%)", color="#7f8c8d",
    )

    for bars in (bars_never, bars_accuracy, bars_always):
        ax.bar_label(bars, fmt="%.1f", padding=2, fontsize=7.5)

    ax.set_ylabel("Final-system EM")
    ax.set_title("Retrieval within the Decomposition Path", fontsize=14, pad=12)
    ax.set_xticks(x)
    ax.set_xticklabels(DATASET_LABELS)
    ax.set_ylim(0, 61)
    legend = ax.legend(loc="upper left", fontsize=8.6, frameon=False)
    legend.get_texts()[1].set_color("#c62828")
    legend.get_texts()[1].set_fontweight("bold")
    ax.grid(axis="y", linestyle="--", alpha=0.28)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)

    fig.tight_layout()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(args.out, bbox_inches="tight")
    plt.close(fig)
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
