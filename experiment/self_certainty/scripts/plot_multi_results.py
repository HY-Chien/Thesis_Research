"""
Plot combined results for multi-dataset SC vs PPL experiment.

Figure 1: AUC comparison bar chart (4 conditions x 2 metrics)
Figure 2: Accuracy vs AUC scatter (show SC is more consistent)
Figure 3: Stability comparison — original vs rewritten AUC delta

Input: exp0_multi_summary.json (generated by exp0_sc_vs_ppl_multi.py)
"""

import json
import os
import numpy as np

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

# ================= Paths =================
SUMMARY_FILE = "/home/S113065528/Adaptive-RAG/experiment/self_certainty/exp0_multi_summary.json"

# Also load per-dataset results for detailed plots
RESULT_DIR = "/home/S113065528/Adaptive-RAG/experiment/self_certainty"
OUTPUT_DIR = "/home/S113065528/Adaptive-RAG/experiment/self_certainty/figures"
# =========================================

os.makedirs(OUTPUT_DIR, exist_ok=True)

BLUE = "#4C72B0"
ORANGE = "#DD8452"
GREEN = "#55A868"
RED = "#C44E52"

with open(SUMMARY_FILE, encoding="utf-8") as f:
    summaries = json.load(f)

# Build lookup
data = {s["name"]: s for s in summaries}

# ============================================================
#  Figure 1: AUC Bar Chart — SC vs PPL across all 4 conditions
# ============================================================
conditions = ["nq_original", "nq_rewritten", "2wiki_original", "2wiki_rewritten"]
labels = ["NQ\nOriginal", "NQ\nRewritten", "2Wiki\nOriginal", "2Wiki\nRewritten"]

auc_sc = [data[c]["auc_sc"] for c in conditions]
auc_ppl = [data[c]["auc_ppl"] for c in conditions]

x = np.arange(len(conditions))
width = 0.35

fig1, ax = plt.subplots(figsize=(10, 6))
bars_sc = ax.bar(x - width/2, auc_sc, width, label="Self-Certainty (SC)", color=BLUE, edgecolor="black", linewidth=0.5)
bars_ppl = ax.bar(x + width/2, auc_ppl, width, label="Perplexity (PPL)", color=ORANGE, edgecolor="black", linewidth=0.5)

ax.set_ylabel("AUC (predicting correct answers)", fontsize=12)
ax.set_title("SC vs PPL: AUC for Separating Correct / Incorrect Answers\n(across datasets & query rewriting)", fontsize=13, fontweight="bold")
ax.set_xticks(x)
ax.set_xticklabels(labels, fontsize=11)
ax.legend(fontsize=11, loc="upper right")
ax.set_ylim(0.4, max(max(auc_sc), max(auc_ppl)) * 1.15)
ax.axhline(y=0.5, color="gray", linestyle="--", linewidth=0.8, label="Random")

# Add value labels on bars
for bars in [bars_sc, bars_ppl]:
    for bar in bars:
        h = bar.get_height()
        ax.text(bar.get_x() + bar.get_width()/2, h + 0.005,
                f"{h:.3f}", ha="center", va="bottom", fontsize=10, fontweight="bold")

fig1.tight_layout()
out1 = os.path.join(OUTPUT_DIR, "exp0_multi_auc_comparison.png")
fig1.savefig(out1, dpi=150, bbox_inches="tight")
print(f"Saved: {out1}")

# ============================================================
#  Figure 2: AUC Delta — How much does rewriting affect AUC?
# ============================================================
fig2, axes = plt.subplots(1, 2, figsize=(12, 5))
fig2.suptitle("AUC Stability Under Query Rewriting\n(smaller |ΔAUC| = more robust to surface form changes)",
              fontsize=13, fontweight="bold")

datasets = ["nq", "2wiki"]
dataset_labels = ["NQ", "2WikiMultiHopQA"]

for idx, (ds, ds_label) in enumerate(zip(datasets, dataset_labels)):
    ax = axes[idx]
    orig = data[f"{ds}_original"]
    rew = data[f"{ds}_rewritten"]

    delta_sc = abs(rew["auc_sc"] - orig["auc_sc"])
    delta_ppl = abs(rew["auc_ppl"] - orig["auc_ppl"])

    bars = ax.bar(
        ["SC", "PPL"],
        [delta_sc, delta_ppl],
        color=[BLUE, ORANGE], width=0.4,
        edgecolor="black", linewidth=0.8,
    )

    for bar, val in zip(bars, [delta_sc, delta_ppl]):
        ax.text(bar.get_x() + bar.get_width()/2, bar.get_height() + 0.002,
                f"{val:.4f}", ha="center", va="bottom", fontsize=12, fontweight="bold")

    ax.set_ylabel("|ΔAUC| (original → rewritten)", fontsize=11)
    ax.set_title(f"{ds_label}", fontsize=12)
    ax.set_ylim(0, max(delta_sc, delta_ppl) * 1.5)

    # Add original/rewritten AUC as text
    txt = (f"Original:  SC={orig['auc_sc']:.3f}  PPL={orig['auc_ppl']:.3f}\n"
           f"Rewritten: SC={rew['auc_sc']:.3f}  PPL={rew['auc_ppl']:.3f}")
    ax.text(0.5, 0.95, txt, transform=ax.transAxes, ha="center", va="top",
            fontsize=9, bbox=dict(boxstyle="round", facecolor="lightyellow", alpha=0.9))

fig2.tight_layout()
out2 = os.path.join(OUTPUT_DIR, "exp0_multi_auc_stability.png")
fig2.savefig(out2, dpi=150, bbox_inches="tight")
print(f"Saved: {out2}")

# ============================================================
#  Figure 3: Summary table as figure (for presentation)
# ============================================================
fig3, ax = plt.subplots(figsize=(10, 4))
ax.axis("off")
ax.set_title("Summary: SC vs PPL across Datasets & Rewriting",
             fontsize=13, fontweight="bold", pad=20)

col_labels = ["Condition", "Accuracy", "AUC (SC)", "AUC (PPL)", "Winner", "ΔAUC SC", "ΔAUC PPL"]
rows = []

for ds, ds_label in zip(datasets, dataset_labels):
    orig = data[f"{ds}_original"]
    rew = data[f"{ds}_rewritten"]
    delta_sc = abs(rew["auc_sc"] - orig["auc_sc"])
    delta_ppl = abs(rew["auc_ppl"] - orig["auc_ppl"])

    for variant, s in [("Original", orig), ("Rewritten", rew)]:
        winner = "SC ✓" if s["auc_sc"] > s["auc_ppl"] else "PPL ✓"
        d_sc = f"{delta_sc:.4f}" if variant == "Original" else "↑"
        d_ppl = f"{delta_ppl:.4f}" if variant == "Original" else "↑"
        rows.append([
            f"{ds_label} {variant}",
            f"{s['accuracy']:.1f}%",
            f"{s['auc_sc']:.4f}",
            f"{s['auc_ppl']:.4f}",
            winner,
            d_sc,
            d_ppl,
        ])

table = ax.table(
    cellText=rows,
    colLabels=col_labels,
    cellLoc="center",
    loc="center",
)
table.auto_set_font_size(False)
table.set_fontsize(10)
table.scale(1.2, 1.8)

# Color the header
for j in range(len(col_labels)):
    table[0, j].set_facecolor("#D5E8D4")
    table[0, j].set_text_props(fontweight="bold")

# Color winner cells
for i, row in enumerate(rows, 1):
    if "SC" in row[4]:
        table[i, 4].set_facecolor("#D6EAF8")
    else:
        table[i, 4].set_facecolor("#FADBD8")

fig3.tight_layout()
out3 = os.path.join(OUTPUT_DIR, "exp0_multi_summary_table.png")
fig3.savefig(out3, dpi=150, bbox_inches="tight")
print(f"Saved: {out3}")

# Print summary to terminal
print("\n" + "=" * 70)
print("SUMMARY")
print("=" * 70)
for s in summaries:
    winner = "SC" if s["auc_sc"] > s["auc_ppl"] else "PPL"
    print(f"  {s['name']:<25} Acc={s['accuracy']:5.1f}%  AUC_SC={s['auc_sc']:.4f}  AUC_PPL={s['auc_ppl']:.4f}  → {winner}")
print()
print(f"All figures saved to: {OUTPUT_DIR}")
